import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { renderReportMarkdown } from "../../src/core/report/markdown";
import { ReportSchema, type Report } from "../../src/core/types";

const fixturesDir = join(__dirname, "../fixtures/reports");

function loadReport(filename: string): Report {
  const raw = readFileSync(join(fixturesDir, filename), "utf8");
  return ReportSchema.parse(JSON.parse(raw));
}

describe("renderReportMarkdown", () => {
  it("renders sample-report.json correctly with heading, commit link, table, claims, and footer", () => {
    const report = loadReport("sample-report.json");
    const md = renderReportMarkdown(report);

    // Heading links to target URL
    expect(md).toContain(
      "# Pramaan evidence report: acme-org/widget-engine#[42](https://github.com/acme-org/widget-engine/issues/42)",
    );

    // Commit link
    expect(md).toContain(
      "**Verified commit:** [a1b2c3d](https://github.com/acme-org/widget-engine/commit/a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2)",
    );

    // Suggested label and disclaimer
    expect(md).toContain("**Suggested label:** **Needs human review**");
    expect(md).toContain(
      "_Suggested label only — Pramaan never closes issues._",
    );

    // Table has header and 4 rows (one per assessment)
    expect(md).toContain(
      "| # | Claim | Verdict | Confidence | Human review |",
    );
    expect(md).toContain(
      "| 1 | Widget.render() throws a TypeError when props.items is undefined | Reproduced | High | No |",
    );
    expect(md).toContain(
      "| 2 | The crash can be triggered by any authenticated user via the /api/widgets endpoint, constituting a denial-of-service vulnerability | Insufficient evidence | Low | Yes |",
    );
    expect(md).toContain(
      "| 3 | The fix should add a null guard before calling props.items.map() on line 47 of src/widget.ts | Contradicted | Medium | No |",
    );
    expect(md).toContain(
      "| 4 | The bug was introduced in version 2.3.0 and is not present in 2.2.x | Not reproduced | None | No |",
    );

    // One section per claim
    expect(md).toContain(
      "### Claim 1: Widget.render() throws a TypeError when props.items is undefined",
    );
    expect(md).toContain(
      "> Widget.render() crashes with a TypeError when props.items is undefined",
    );
    expect(md).toContain(
      "[code](https://github.com/acme-org/widget-engine/blob/a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2/src/widget.ts#L45-L52)",
    );

    // Collapsible block for log
    expect(md).toContain("<details><summary>Output</summary>");
    expect(md).toContain("TypeError: Cannot read properties of undefined");
    expect(md).toContain("</details>");

    // Footer
    expect(md).toContain(
      "Generated by Pramaan at 2026-10-31T18:00:00.000Z using llama3.2:3b, codellama:7b. Verdicts come from code checks, not from the model.",
    );
  });

  it("renders abstained report with zero assessments and displays warning", () => {
    const report = loadReport("abstained-report.json");
    const md = renderReportMarkdown(report);

    // Heading
    expect(md).toContain(
      "# Pramaan evidence report: acme-org/widget-engine#[99](https://github.com/acme-org/widget-engine/issues/99)",
    );

    // Null commit
    expect(md).toContain("**Verified commit:** No checkout was needed");

    // Triage label
    expect(md).toContain(
      "**Suggested label:** **Needs more information**",
    );
    expect(md).toContain(
      "_Suggested label only — Pramaan never closes issues._",
    );

    // Abstained warning
    expect(md).toContain("> [!WARNING]");
    expect(md).toContain(
      "**Claim extraction abstained:** The issue description contains no technical details or steps to reproduce",
    );
    expect(md).toContain("A human should read the report directly.");

    // Table with 0 rows
    expect(md).toContain(
      "| # | Claim | Verdict | Confidence | Human review |",
    );
    expect(md).not.toContain("| 1 |");
  });

  it("escapes user-controlled text, handles backticks without breaking fences, and truncates 60-line log", () => {
    const report = loadReport("adversarial-report.json");
    const md = renderReportMarkdown(report);

    // Escapes <script> tag
    expect(md).not.toContain("<script>");
    expect(md).toContain("&lt;script&gt;alert(1)&lt;/script&gt;");

    // Escapes pipe in table cell
    expect(md).toContain("\\| with pipe and");

    // Escapes leading # in statement / quote
    expect(md).toContain("\\# Critical bug");

    // Truncates 60-line log to 40 lines with note
    expect(md).toContain("line 40");
    expect(md).not.toContain("line 41: after cutoff");
    expect(md).toContain("… (20 more lines)");

    // Safe code fence doesn't break even if log contains ```
    expect(md).toContain("````");
    expect(md).toContain("```embedded code fence```");

    // Footer with no models
    expect(md).toContain("using no model.");
  });
});
